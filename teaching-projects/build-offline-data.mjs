const safeStringify = (value) => JSON.stringify(value)
  .replaceAll("\u2028", "\\u2028")
  .replaceAll("\u2029", "\\u2029");

export const renderOfflineBundle = (project) => {
  const files = Object.fromEntries(project.files.map((requestPath) => {
    const sourcePath = join(projectRoot, project.directory, requestPath);
    return [requestPath, readFileSync(sourcePath, "utf8")];
  }));
  const digest = createHash("sha256")
    .update(JSON.stringify(files))
    .digest("hex");

  return `/* Generated by build-offline-data.mjs. Source digest: ${digest} */\n` +
`(() => {\n` +
`  if (window.location.protocol !== "file:") return;\n` +
`  const files = ${safeStringify(files)};\n` +
`  const nativeFetch = window.fetch.bind(window);\n` +
`  const normalizedUrl = (value) => {\n` +
`    const url = new URL(value, window.location.href);\n` +
`    url.search = "";\n` +
`    url.hash = "";\n` +
`    return url.href;\n` +
`  };\n` +
`  const localFiles = new Map(Object.entries(files).map(([path, contents]) => [\n` +
`    normalizedUrl(path),\n` +
`    { contents, type: path.endsWith(".json") ? "application/json" : "text/csv" }\n` +
`  ]));\n` +
`  window.fetch = (input, init) => {\n` +
`    const requestUrl = typeof input === "string" || input instanceof URL ? input.toString() : input.url;\n` +
`    const localFile = localFiles.get(normalizedUrl(requestUrl));\n` +
`    if (!localFile) return nativeFetch(input, init);\n` +
`    return Promise.resolve(new Response(localFile.contents, {\n` +
`      status: 200,\n` +
`      headers: { "Content-Type": localFile.type + "; charset=utf-8" }\n` +
`    }));\n` +
`  };\n` +
`})();\n`;
};

export const buildOfflineBundles = () => {
  for (const project of offlineProjects) {
    const outputPath = join(projectRoot, project.directory, "offline-data.js");
    writeFileSync(outputPath, renderOfflineBundle(project));
    console.log(`Built ${relative(projectRoot, outputPath)} for ${project.name}.`);
  }
};

const entryPath = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (import.meta.url === entryPath) buildOfflineBundles();
